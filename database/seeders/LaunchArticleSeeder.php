    public function run(): void
    {
        $category = ArticleCategory::query()->updateOrCreate(
            ['name' => 'دليل فلاتر وتحلية المياه'],
            [
                'description' => 'مقالات عملية تساعد على اختيار الفلتر وفهم مراحل التحلية ومواعيد الصيانة وأسباب الأعطال الشائعة.',
                'is_active' => true,
            ],
        );
        $serviceIds = Service::query()->pluck('id', 'name');
        $articles = $this->articles();
        $titles = collect($articles)->pluck('title');

        ArticleCategory::query()->whereKeyNot($category->id)->update(['is_active' => false]);
        Article::query()->whereNotIn('title', $titles)->update(['status' => 'draft', 'published_at' => null]);

        $saved = collect();
        foreach ($articles as $data) {
            $article = Article::query()->updateOrCreate(['title' => $data['title']], [
                'article_category_id' => $category->id,
                'excerpt' => $data['excerpt'],
                'body' => $data['body'],
                'featured_image' => config('site.article_featured_images.'.$data['title']),
                'featured_image_alt' => $data['title'],
                'featured_image_caption' => 'صورة توضيحية لمقال '.$data['title'],
                'status' => 'published',
                'published_at' => now(),
            ]);

            $article->services()->sync(
                collect($data['services'])->map(fn (string $name) => $serviceIds->get($name))->filter()->values()
            );
            $article->seo()->updateOrCreate([], [
                'meta_title' => $data['title'],
                'meta_description' => $data['excerpt'],
                'focus_keyword' => $data['keyword'],
                'related_terms' => implode("\n", $data['related_terms']),
                'robots' => 'index,follow,max-image-preview:large',
                'og_title' => $data['title'],
                'og_description' => $data['excerpt'],
                'schema_type' => 'Article',
            ]);
            $saved->push($article);
        }

        $saved->each(function (Article $article, int $index) use ($saved): void {
            $related = collect(range(1, min(3, $saved->count() - 1)))
                ->map(fn (int $offset) => $saved->get(($index + $offset) % $saved->count())?->id)
                ->filter();
            $article->relatedArticles()->sync($related);
        });
    }

