    public function run(): void
    {
        $materialIds = Material::query()->pluck('id', 'name');
        $publishedNames = collect($this->catalog())->flatMap(fn (array $category) => collect($category['services'])->pluck('name'));

        Service::query()->whereNotIn('name', $publishedNames)->update([
            'status' => 'draft',
            'is_featured' => false,
            'is_popular' => false,
            'published_at' => null,
        ]);
        ServiceCategory::query()->update(['is_active' => false]);

        $globalOrder = 0;
        foreach ($this->catalog() as $categoryIndex => $categoryData) {
            $category = ServiceCategory::query()->updateOrCreate(
                ['name' => $categoryData['name']],
                [
                    'excerpt' => $categoryData['excerpt'],
                    'description' => $categoryData['description'],
                    'sort_order' => $categoryIndex + 1,
                    'is_active' => true,
                ],
            );

            foreach ($categoryData['services'] as $data) {
                $globalOrder++;
                $featuredImage = config('site.service_featured_images.'.$data['name']);
                $service = Service::query()->updateOrCreate(
                    ['name' => $data['name']],
                    [
                        'service_category_id' => $category->id,
                        'parent_service_id' => null,
                        'image_source_folder' => null,
                        'excerpt' => $data['definition'],
                        'content' => $data['content'],
                        'types' => $this->lines($data['types']),
                        'use_cases' => $this->lines($data['cases']),
                        'materials_details' => $this->lines($data['parts']),
                        'advantages' => $this->lines($data['advantages']),
                        'disadvantages' => $this->lines($data['notes']),
                        'installation_steps' => $this->lines($data['steps']),
                        'price_factors' => $this->lines($data['factors']),
                        'selection_tips' => $this->lines($data['tips']),
                        'cta' => $data['cta'],
                        'featured_image' => $featuredImage,
                        'featured_image_alt' => $data['name'],
                        'featured_image_caption' => 'صورة توضيحية لخدمة '.$data['name'],
                        'sort_order' => $globalOrder,
                        'is_active' => true,
                        'status' => 'published',
                        'published_at' => now(),
                        'is_featured' => $globalOrder <= 6,
                        'is_popular' => in_array($globalOrder, [1, 3, 4, 8], true),
                        'is_price_published' => false,
                        'price_from' => null,
                        'price_to' => null,
                        'price_unit' => null,
                        'price_note' => null,
                    ],
                );

                $service->materials()->sync(
                    collect($data['materials'])->map(fn (string $name) => $materialIds->get($name))->filter()->values()
                );

                $faqIds = collect($data['faqs'])->map(function (array $faqData, int $index) {
                    return Faq::query()->updateOrCreate(
                        ['question' => $faqData['question']],
                        ['answer' => $faqData['answer'], 'sort_order' => $index + 1, 'is_active' => true],
                    )->id;
                });
                $service->faqs()->sync($faqIds);

                $service->seo()->updateOrCreate([], [
                    'meta_title' => $data['name'],
                    'meta_description' => $data['definition'],
                    'focus_keyword' => $data['keyword'],
                    'related_terms' => $this->lines($data['related_terms']),
                    'robots' => 'index,follow,max-image-preview:large',
                    'og_title' => $data['name'],
                    'og_description' => $data['definition'],
                    'schema_type' => 'Service',
                ]);
            }
        }

        Cache::forget('navigation.service-categories');
    }

